def js(v):
    return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    p = "quiz.js"
    s = io.open(p, encoding="utf-8").read()

    if "第三批 100 題" in s:
        sys.exit("quiz.js 裡已經有第三批題目了——這支只能跑一次，重跑會插入重複題。")

    # 1) 補新來源。掛在最後一個既有來源後面。
    anchor = '  "KDIGO_Anemia2026": "KDIGO 2026 Clinical Practice Guideline for Anemia in CKD",'
    if anchor not in s:
        sys.exit("找不到 QUIZ_SRC 的錨點，quiz.js 結構可能改過了，先確認再跑。")
    add = "".join(f'\n  {js(k)}: {js(v)},' for k, v in NEW_SRC.items())
    s = s.replace(anchor, anchor + add, 1)

    # 2) 題目插到 QUIZ 陣列末端
    end = s.index("\n];", s.index("const QUIZ = ["))
    blocks = ["\n\n/* ── 第三批 100 題（200 → 300，來源已逐題查證）── */"]
    for x in Q:
        opts = ",".join(js(o) for o in x["o"])
        blocks.append(
            f'\n{{c:{js(x["c"])}, k:{js(x["k"])},\n'
            f' q:{js(x["q"])},\n'
            f' o:[{opts}],\n'
            f' a:{x["a"]},\n'
            f' e:{js(x["e"])},\n'
            f' src:{js(x["src"])}}},')
    s = s[:end] + "".join(blocks) + s[end:]
    io.open(p, "w", encoding="utf-8").write(s)

    print(f"新增 {len(Q)} 題")
    print("分類:", dict(collections.Counter(x["c"] for x in Q)))
    print("來源:", dict(collections.Counter(x["src"] for x in Q)))
    print("知識卡:", len({x["k"] for x in Q}), "張不重複")
    return 0


if __name__ == "__main__":
    sys.exit(main())
